/** This file makes the text of the generated table of `lineBreaks` from the two property files of Unicode. */

const unit = 0x110000;

/** The characters that name a class in the table. Base 36 digits hold the lengths, so these characters are not digits. */
const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ!#$%&()*+-./:;<=>?@[]^_{|}~";

/** This function calls `visit` with the first code point, the last code point and the value of each data line of a property file. */
function eachRange(text: string, visit: (first: number, last: number, value: string) => void): void {
  for (const line of text.split("\n")) {
    const match = /^\s*(?:#\s*@missing:\s*)?([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)/u.exec(line);
    if (match === null) continue;
    const first = Number.parseInt(match[1]!, 16);
    visit(first, match[2] === undefined ? first : Number.parseInt(match[2], 16), match[3]!);
  }
}

/** This function resolves a class of `LineBreak.txt` by the table of the rule LB1 of UAX #14. */
export function resolveClass(name: string, code: number): string {
  if (name === "AI" || name === "SG" || name === "XX") return "AL";
  if (name === "CJ") return "NS";
  if (name === "SA") return /^[\p{Mn}\p{Mc}]$/u.test(String.fromCodePoint(code)) ? "CM" : "AL";
  return name;
}

/** The lengths of the runs of equal values over all the code points. */
function runsOf(values: Uint8Array): { value: number; length: number }[] {
  const runs: { value: number; length: number }[] = [];
  for (const value of values) {
    const last = runs.at(-1);
    if (last?.value === value) last.length++;
    else runs.push({ value, length: 1 });
  }
  return runs;
}

/** The table in text form. */
export interface LineTable {
  readonly classNames: readonly string[];
  /** Each run is a length in base 36 and a character of `alphabet` that names its class. */
  readonly classes: string;
  /** The lengths in base 36, with a space between them. The first run is not East Asian, and the runs alternate. */
  readonly eastAsian: string;
}

/** This function makes the table from the text of `LineBreak.txt` and of `EastAsianWidth.txt`. */
export function makeTable(lineBreak: string, eastAsianWidth: string): LineTable {
  const names = new Map<string, number>();
  const indexOf = (name: string): number => {
    const known = names.get(name);
    if (known !== undefined) return known;
    if (names.size === alphabet.length) throw new Error("the alphabet of the table is too small");
    names.set(name, names.size);
    return names.size - 1;
  };
  const classes = new Uint8Array(unit).fill(indexOf("AL"));
  eachRange(lineBreak, (first, last, value) => {
    for (let code = first; code <= last; code++) classes[code] = indexOf(resolveClass(value, code));
  });
  const east = new Uint8Array(unit);
  eachRange(eastAsianWidth, (first, last, value) => {
    east.fill(value === "F" || value === "W" || value === "H" ? 1 : 0, first, last + 1);
  });
  const eastRuns = runsOf(east);
  if (eastRuns[0]!.value !== 0) throw new Error("the first code point is East Asian");
  return {
    classNames: [...names.keys()],
    classes: runsOf(classes).map((run) => `${run.length.toString(36)}${alphabet[run.value]!}`).join(""),
    eastAsian: eastRuns.map((run) => run.length.toString(36)).join(" "),
  };
}

/** This function gives the source of the generated file. */
export function tableSource(table: LineTable, version: string): string {
  return [
    `// Generated by \`pnpm --filter @typeset/conformance tables\` from Unicode ${version}. Do not edit.`,
    `export const unicodeVersion = ${JSON.stringify(version)};`,
    `export const classNames = ${JSON.stringify(table.classNames.join(" "))}.split(" ");`,
    `export const classRuns = ${JSON.stringify(table.classes)};`,
    `export const eastAsianRuns = ${JSON.stringify(table.eastAsian)};`,
    "",
  ].join("\n");
}
