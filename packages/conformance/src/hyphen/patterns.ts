import type { HyphenSource, PatternSet } from "@mark1russell7/typeset/hyphen";

/** The data of a pattern file. */
export interface PatternData extends PatternSet {
  /** The lines of the file header up to the end of its license, with no comment mark. The license says that they stay with the data. */
  readonly notice: readonly string[];
}

/** This function gives the text in the braces after a TeX command, without comments. It gives "" when the file has no such command. */
function groupOf(lines: readonly string[], command: string): string {
  const text = lines.join("\n");
  const start = text.indexOf(`${command}{`);
  if (start < 0) return "";
  const open = start + command.length + 1;
  return text.slice(open, text.indexOf("}", open));
}

/** This function reads a pattern file of the project `tex-hyphen`. */
export function parsePatterns(text: string): PatternData {
  const lines = text.split(/\r?\n/u);
  const end = lines.findIndex((line) => line.startsWith("% hyphenmins:"));
  if (end < 0) throw new Error("the file has no field hyphenmins");
  const typesetting = lines.slice(end).findIndex((line) => line.includes("typesetting:"));
  if (typesetting < 0) throw new Error("the file has no typesetting values");
  const left = /left:\s*(\d)/u.exec(lines[end + typesetting + 1]!);
  const right = /right:\s*(\d)/u.exec(lines[end + typesetting + 2]!);
  if (left === null || right === null) throw new Error("the file has no left and right values");
  // A TeX comment goes from a % to the end of the line. A cut at the first % takes one pass on each line
  const code = lines.map((line) => {
    const comment = line.indexOf("%");
    return comment < 0 ? line : line.slice(0, comment);
  });
  const words = (group: string): string => group.split(/\s+/u).filter((word) => word !== "").join(" ");
  const patterns = words(groupOf(code, "\\patterns"));
  if (patterns === "") throw new Error("the file has no patterns");
  return {
    patterns,
    exceptions: words(groupOf(code, "\\hyphenation")),
    left: Number(left[1]),
    right: Number(right[1]),
    notice: lines.slice(0, end).map((line) => line.replace(/^%\s?/u, "").trimEnd()),
  };
}

/** This function gives the source of the generated module of a language. Each note is a line comment after the line of the generator. */
export function setSource(data: PatternData, source: HyphenSource, notes: readonly string[] = []): string {
  const set = { patterns: data.patterns, exceptions: data.exceptions, left: data.left, right: data.right };
  return [
    "/*!",
    ...data.notice.map((line) => ` * ${line}`.trimEnd()),
    " */",
    "// Generated by `pnpm --filter @typeset/conformance tables`. Do not edit.",
    ...notes.map((note) => `// ${note}`),
    'import { hyphenator, type HyphenSource } from "../hyphen.ts";',
    "",
    "/** The origin of this set, and its result on its word list. */",
    `export const source: HyphenSource = ${JSON.stringify(source)};`,
    "",
    "/** This function gives the hyphen places of a word. Give it to the hook `hyphenate` of `paragraphOf`. */",
    `export const hyphenate: (word: string) => readonly number[] = /* @__PURE__ */ hyphenator(${JSON.stringify(set)});`,
    "",
  ].join("\n");
}
